    /// 照原圖寬高比置中，填滿較短的那一邊
    func path(in rect: CGRect) -> Path {
        let height = min(rect.height, rect.width / Self.aspect), width = height * Self.aspect
        let origin = CGPoint(x: rect.midX - width / 2, y: rect.midY - height / 2)
        var path = Path()
        for loop in Self.outlines {
            let points = loop.map { CGPoint(x: origin.x + $0.x * width, y: origin.y + $0.y * height) }
            func mid(_ i: Int) -> CGPoint {
                let a = points[i % points.count], b = points[(i + 1) % points.count]
                return CGPoint(x: (a.x + b.x) / 2, y: (a.y + b.y) / 2)
            }
            path.move(to: mid(0))
            for i in 1...points.count { path.addQuadCurve(to: mid(i), control: points[i % points.count]) }
            path.closeSubpath()
        }
        return path
    }
